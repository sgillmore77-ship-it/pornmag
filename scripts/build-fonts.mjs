// Copies the self-hosted font files from @fontsource into public/fonts and
// writes src/app/fonts.css, so the files have stable URLs that pages can
// preload (see FONT_PRELOADS in src/lib/theme.ts). Re-run after changing
// font packages: `node scripts/build-fonts.mjs`.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const SOURCES = [
  "@fontsource-variable/bodoni-moda/opsz.css",
  "@fontsource/hanken-grotesk/400.css",
  "@fontsource/hanken-grotesk/500.css",
  "@fontsource/hanken-grotesk/600.css",
  "@fontsource/hanken-grotesk/700.css",
  "@fontsource/anton/400.css",
  "@fontsource/archivo/400.css",
  "@fontsource/archivo/500.css",
  "@fontsource/archivo/600.css",
  "@fontsource/archivo/700.css",
  "@fontsource/instrument-serif/400.css",
  "@fontsource/instrument-serif/400-italic.css",
  "@fontsource/schibsted-grotesk/400.css",
  "@fontsource/schibsted-grotesk/500.css",
  "@fontsource/schibsted-grotesk/600.css",
  "@fontsource/schibsted-grotesk/700.css",
  "@fontsource/ibm-plex-mono/400.css",
  "@fontsource/ibm-plex-mono/500.css",
];

mkdirSync("public/fonts", { recursive: true });
let css = "/* Generated by scripts/build-fonts.mjs — do not edit. */\n";
let files = 0;
for (const spec of SOURCES) {
  const path = require.resolve(spec);
  let text = readFileSync(path, "utf8");
  // Keep woff2 only (every supported browser has it).
  text = text.replace(/,\s*url\([^)]+\.woff\)\s*format\('woff'\)/g, "");
  text = text.replace(/url\(\.\/files\/([^)]+\.woff2)\)/g, (_m, name) => {
    copyFileSync(join(dirname(path), "files", name), join("public/fonts", name));
    files += 1;
    return `url(/fonts/${name})`;
  });
  css += `\n/* ${spec} */\n${text.trim()}\n`;
}
writeFileSync("src/app/fonts.css", css);
console.log(`Wrote src/app/fonts.css and ${files} font files to public/fonts`);
